# ============================================================
# R 语言数据结构 - 向量和矩阵
# 运行：Rscript 01_向量和矩阵.R
# ============================================================

cat("=== 向量 Vector ===\n")

# 创建向量
v <- c(1, 2, 3, 4, 5)
cat("普通向量:", v, "\n")

# 序列
v2 <- 1:10
cat("序列 1:10:", v2, "\n")

v3 <- seq(1, 10, by = 2)
cat("seq 步长2:", v3, "\n")

v4 <- rep("A", 5)
cat("rep 重复:", v4, "\n")

# 向量运算
cat("\n向量运算:\n")
a <- c(1, 2, 3)
b <- c(4, 5, 6)
cat("a + b =", a + b, "\n")
cat("a * b =", a * b, "\n")
cat("a ^ 2 =", a ^ 2, "\n")

# 常用函数
cat("\n常用函数:\n")
nums <- c(5, 2, 8, 1, 9, 3)
cat("  长度:", length(nums), "\n")
cat("  总和:", sum(nums), "\n")
cat("  均值:", mean(nums), "\n")
cat("  中位数:", median(nums), "\n")
cat("  方差:", var(nums), "\n")
cat("  标准差:", sd(nums), "\n")
cat("  最大值:", max(nums), "\n")
cat("  最小值:", min(nums), "\n")
cat("  排序:", sort(nums), "\n")

# 索引（从 1 开始！）
cat("\n向量索引:\n")
v <- c("a", "b", "c", "d", "e")
cat("v[1] =", v[1], "\n")
cat("v[2:4] =", v[2:4], "\n")
cat("v[c(1,3,5)] =", v[c(1,3,5)], "\n")
cat("v[-1] =", v[-1], "\n")  # 删除第一个

# 逻辑索引
cat("\n逻辑索引:\n")
nums <- 1:10
cat("大于5的:", nums[nums > 5], "\n")

# 命名向量
cat("\n命名向量:\n")
scores <- c(语文=95, 数学=88, 英语=92)
cat("数学成绩:", scores["数学"], "\n")

# ============================================================
# 矩阵 Matrix
# ============================================================

cat("\n=== 矩阵 Matrix ===\n")

# 创建矩阵
m <- matrix(1:9, nrow=3, ncol=3)
cat("3x3矩阵:\n")
print(m)

m2 <- matrix(1:6, nrow=2, byrow=TRUE)
cat("按行填充的2x3矩阵:\n")
print(m2)

# 矩阵运算
cat("\n矩阵运算:\n")
m1 <- matrix(1:4, nrow=2)
m2 <- matrix(5:8, nrow=2)
cat("矩阵相加:\n")
print(m1 + m2)

cat("矩阵相乘:\n")
print(m1 %*% m2)

# 矩阵索引
cat("\n矩阵索引:\n")
cat("m[1,1] =", m[1,1], "\n")
cat("m[2,] =", m[2,], "\n")
cat("m[,3] =", m[,3], "\n")

# 行列名
rownames(m) <- c("行1", "行2", "行3")
colnames(m) <- c("列1", "列2", "列3")
cat("\n带行列名的矩阵:\n")
print(m)

cat("\n=== 运行完成 ===\n")
